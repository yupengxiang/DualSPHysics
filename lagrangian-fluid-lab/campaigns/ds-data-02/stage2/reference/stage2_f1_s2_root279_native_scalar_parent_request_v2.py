#!/usr/bin/env python3
"""Additive ROOT279 source request builder for the corrected V2 chain.

The consumed request builder remains byte-for-byte untouched.  This wrapper
reuses its strict ROOT277/278/310 and ROOT279 source joins, but binds the
additive parent and compact workers and extends the static closure with the
legacy modules those workers import.  It never opens deferred native files
and always leaves execution disabled for the root forwarder.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
from pathlib import Path
import tempfile
from typing import Any


HERE = Path(__file__).resolve().parent
V1_PATH = HERE / "stage2_f1_s2_root279_native_scalar_parent_request_v1.py"
PARENT_V2 = HERE / "stage2_f1_s2_root279_native_scalar_parent_worker_v2.py"
COMPACT_V2 = HERE / "stage2_f1_s2_root279_native_compact_worker_v2.py"
VARIANT_SCHEMA = "ds02.stage2.f1-s2.root279-native-scalar-parent-request.v2"
PARENT_MANIFEST_SCHEMA = "ds02.stage2.f1-s2.root279-native-scalar-parent-manifest.v2"


class BuildV2Failure(RuntimeError):
    pass


def _load_v1() -> Any:
    spec = importlib.util.spec_from_file_location("root279_parent_request_v1_for_v2", V1_PATH)
    if spec is None or spec.loader is None:
        raise BuildV2Failure(f"cannot load consumed ROOT279 request builder: {V1_PATH}")
    value = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(value)
    return value


V1 = _load_v1()
# Patch only the globals read by V1.build.  The V1 file on disk is never
# modified and its source joins remain the authority for this additive build.
V1.COMPACT = COMPACT_V2
V1.PARENT_WORKER = PARENT_V2
V1.VARIANT_SCHEMA = VARIANT_SCHEMA
V1.PARENT_MANIFEST_SCHEMA = PARENT_MANIFEST_SCHEMA


def _load_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise BuildV2Failure(f"cannot read generated JSON {path}: {exc}") from exc
    if not isinstance(value, dict):
        raise BuildV2Failure(f"generated JSON is not an object: {path}")
    return value


def _write(path: Path, value: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _augment(result: dict[str, Any]) -> dict[str, Any]:
    manifest_path = Path(result["manifest_path"]).absolute()
    request_path = Path(result["request_path"]).absolute()
    package_path = Path(result["package_path"]).absolute()
    manifest = _load_json(manifest_path)
    request = _load_json(request_path)
    package = _load_json(package_path)
    if manifest.get("schema") != PARENT_MANIFEST_SCHEMA:
        raise BuildV2Failure("V2 builder did not emit the additive parent manifest schema")
    if request.get("variant_schema") != VARIANT_SCHEMA:
        raise BuildV2Failure("V2 builder did not emit the additive request variant")

    # V2 workers import the consumed V1 parent and compact modules.  Those
    # imports must be part of the frozen static closure even though the V1
    # builder only records the command entry point.
    extra_paths = (V1.PARENT_WORKER, V1.COMPACT)
    extras: dict[str, dict[str, Any]] = {}
    for path in extra_paths:
        record = V1._record(Path(path), f"ROOT279 V2 transitive source: {Path(path).name}")
        extras[record["path"]] = record

    closure = manifest.get("source_closure")
    if not isinstance(closure, dict) or not isinstance(closure.get("records"), list):
        raise BuildV2Failure("parent manifest source closure is malformed")
    records: dict[str, dict[str, Any]] = {
        item["path"]: item for item in closure["records"]
        if isinstance(item, dict) and isinstance(item.get("path"), str)
    }
    records.update(extras)
    ordered = [records[key] for key in sorted(records)]
    identity = V1._identity_digest(ordered)
    closure["records"] = ordered
    closure["complete"] = True
    manifest["source_identity_digest"] = identity
    manifest["compact_manifest"]["source_identity_digest"] = identity
    manifest["scalar_manifest"]["source_identity"]["source_identity_digest"] = identity

    # The manifest itself is newly generated by this wrapper.  Recompute its
    # record before writing the request so the request binds exact file bytes,
    # rather than the pre-augmentation V1 record.
    _write(manifest_path, manifest)
    manifest_record = V1._record(manifest_path, "ROOT279 V2 parent manifest")
    static: dict[str, dict[str, Any]] = {
        item["path"]: item for item in request.get("input_records", {}).values()
        if isinstance(item, dict) and isinstance(item.get("path"), str)
    }
    static.update(records)
    static[manifest_record["path"]] = manifest_record
    request["source_identity_digest"] = identity
    request["parent_manifest"] = manifest_record
    request["input_records"] = {key: static[key] for key in sorted(static)}
    request["input_files"] = sorted(static)
    request["input_sha256"] = {key: static[key]["sha256"] for key in sorted(static)}
    request["command"] = [
        str(V1._abs(V1.PYTHON)), str(V1._abs(PARENT_V2)), "--run",
        "--manifest", str(manifest_path), "--attempt-root", "{attempt_root}",
    ]
    request["source_binding"]["source_identity_digest"] = identity
    request["source_binding"]["parent_worker_sha256"] = extras[str(V1._abs(V1.PARENT_WORKER))]["sha256"]
    request["source_binding"]["compact_worker_sha256"] = extras[str(V1._abs(V1.COMPACT))]["sha256"]
    request["status"] = "SOURCE_PREPARED_PARENT_AFTER_RESERVATION_REQUIRED"
    request["execution_allowed"] = False
    request["launch_disabled"] = True
    request["native_payload_read"] = False
    request["solver_launch"] = False
    request["gencase_launch"] = False
    _write(request_path, request)
    request_record = V1._record(request_path, "ROOT279 V2 parent source request")
    package["schema"] = "ds02.stage2.f1-s2.root279-native-scalar-parent-package.v2"
    package["manifest"] = manifest_record
    package["request"] = request_record
    package["source_identity_digest"] = identity
    package["parent_worker_sha256"] = extras[str(V1._abs(V1.PARENT_WORKER))]["sha256"]
    package["compact_worker_sha256"] = extras[str(V1._abs(V1.COMPACT))]["sha256"]
    package["scientific_qualification"] = {"QI": "UNKNOWN", "QN": "UNKNOWN", "QE": "UNKNOWN", "scientific_credit": 0}
    _write(package_path, package)
    result.update({"manifest_path": str(manifest_path), "request_path": str(request_path),
                   "package_path": str(package_path), "manifest": manifest, "request": request,
                   "package": package})
    return result


def build(args: argparse.Namespace) -> dict[str, Any]:
    return _augment(V1.build(args))


def _self_test() -> None:
    with tempfile.TemporaryDirectory(prefix="root279-parent-request-v2-") as value:
        root = Path(value)
        # This is a source-only boundary test.  It intentionally does not
        # fabricate ROOT277/278/310 terminal proofs or touch deferred native
        # files; the full child→compact→scalar chain is tested by parent V2.
        assert V1.COMPACT == COMPACT_V2
        assert V1.PARENT_WORKER == PARENT_V2
        assert V1.VARIANT_SCHEMA == VARIANT_SCHEMA
        tiny = root / "tiny.py"; tiny.write_text("print('fixture')\n", encoding="utf-8")
        record = V1._record(tiny, "tiny source")
        assert record["sha256"] and record["bytes"] > 0
    print("PASS_ROOT279_PARENT_REQUEST_V2_BINDS_ADDITIVE_CHAIN_WITHOUT_NATIVE_READ")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--self-test", action="store_true")
    mode.add_argument("--build", action="store_true")
    parser.add_argument("--root279-manifest", type=Path)
    parser.add_argument("--root279-request", type=Path)
    parser.add_argument("--same-proof", type=Path)
    parser.add_argument("--half-proof", type=Path)
    parser.add_argument("--root310-proof", type=Path)
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--cwd", type=Path, default=HERE.parents[5])
    args = parser.parse_args(argv)
    try:
        if args.self_test:
            _self_test(); return 0
        required = (args.root279_manifest, args.root279_request, args.same_proof,
                    args.half_proof, args.root310_proof, args.output_dir)
        if any(item is None for item in required):
            parser.error("--build requires ROOT279 manifest/request, ROOT277/278 proofs, ROOT310 proof and output directory")
        result = build(args)
        print(json.dumps({"status": "SOURCE_PREPARED_WAITING_PARENT_ROOT279_NATIVE_CHAIN_V2",
                          "manifest": result["manifest_path"], "request": result["request_path"],
                          "package": result["package_path"], "scientific_credit": 0}, sort_keys=True))
        return 0
    except (BuildV2Failure, V1.BuildFailure, OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"FAILED_ROOT279_NATIVE_SCALAR_PARENT_REQUEST_V2: {exc}")
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
