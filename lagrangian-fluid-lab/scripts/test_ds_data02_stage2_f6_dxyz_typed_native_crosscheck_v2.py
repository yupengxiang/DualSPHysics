def stat_ref(path: Path, rows: int | None = None) -> dict[str, object]:
    value = subject._stat(path, "fixture")
    value.update({"sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "rows": rows})
    return value


def runparts_text(*, order: list[str] | None = None, second_time: str = "0.1", nout: str = "3", footer: bool = False, duplicate: bool = False, missing: bool = False, malformed_count: bool = False) -> str:
    columns = list(order or subject.RUNPARTS_COLUMNS)
    if duplicate:
        columns[-1] = columns[-2]
    if missing:
        columns = columns[:-1]
    rows: list[dict[str, str]] = []
    for part, time_s in (("0", "0.0"), ("1", second_time)):
        values: dict[str, str] = {}
        for name in subject.RUNPARTS_COLUMNS:
            values[name] = "0" if name in subject.RUNPARTS_INT_COLUMNS else "0.0"
        values.update({"Part": part, "TimeStep [s]": time_s, "Steps": part})
        if part == "1":
            values.update({"NpOut": nout, "NpOutPos": nout})
        if malformed_count and part == "1":
            values["NpOut"] = "3.5"
        rows.append(values)
    lines = [";".join(columns)]
    lines.extend(";".join(row.get(name, "") for name in columns) for row in rows)
    if footer:
        lines.extend(["# official footer", "# generated by fixture"])
    return "\n".join(lines) + "\n"


class F6DxyzCrosscheckV2Tests(unittest.TestCase):
    def _native(self) -> dict[tuple[int, int], dict[str, object]]:
        return {
            (0, 10): {"native_motive_code": 1},
            (0, 11): {"native_motive_code": 1},
            (0, 12): {"native_motive_code": 1},
        }

    def test_partout_exact_identity_and_motive(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "PartOut.csv"
            path.write_text(
                "PartOut,Motive,Idp,Pos.x [m],Pos.y [m],Pos.z [m],Rhop [kg/m^3]\n"
                "1,1,10,0.1,0.2,0.3,1000\n"
                "1,1,11,0.2,0.3,0.4,1001\n"
                "1,1,12,0.3,0.4,0.5,1002\n",
                encoding="utf-8",
            )
            rows, evidence = subject._read_partout(path, stat_ref(path, 3), self._native())
            self.assertEqual(set(rows), set(self._native()))
            self.assertEqual(evidence["rows"], 3)
            self.assertEqual(rows[(0, 11)]["motive_code"], 1)

    def test_partout_wrong_id_or_motive_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "PartOut.csv"
            path.write_text(
                "PartOut,Motive,Idp,Pos.x [m],Pos.y [m],Pos.z [m],Rhop [kg/m^3]\n"
                "1,2,10,0.1,0.2,0.3,1000\n"
                "1,1,11,0.2,0.3,0.4,1001\n"
                "1,1,999,0.3,0.4,0.5,1002\n",
                encoding="utf-8",
            )
            with self.assertRaises(subject.CrosscheckError):
                subject._read_partout(path, stat_ref(path, 3), self._native())

    def test_runparts_totals_and_saved_times_are_source_bound(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "RunPARTs.csv"
            path.write_text(runparts_text(), encoding="utf-8")
            summary = {"timeline": {"time_s": [0.0, 0.1]}}
            native = {"native_decode": {"runparts_totals": {"NpOut": 3, "NpOutPos": 3, "NpOutRho": 0, "NpOutMov": 0}}}
            result = subject._read_runparts(path, stat_ref(path, 2), summary, native)
            self.assertEqual(result["totals"], {"NpOut": 3, "NpOutPos": 3, "NpOutRho": 0, "NpOutMov": 0})
            self.assertEqual(result["max_saved_time_delta_s"], 0.0)
            self.assertEqual(result["column_count"], 26)

    def test_runparts_reordered_header_uses_named_columns(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "RunPARTs.csv"
            order = list(reversed(subject.RUNPARTS_COLUMNS))
            path.write_text(runparts_text(order=order), encoding="utf-8")
            native = {"native_decode": {"runparts_totals": {"NpOut": 3, "NpOutPos": 3, "NpOutRho": 0, "NpOutMov": 0}}}
            result = subject._read_runparts(path, stat_ref(path, 2), {"timeline": {"time_s": [0.0, 0.1]}}, native)
            self.assertEqual(result["totals"]["NpOutPos"], 3)
            self.assertEqual(result["column_names"], order)

    def test_runparts_accepts_thousands_separator_and_footer_comments(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "RunPARTs.csv"
            path.write_text(runparts_text(nout="1,234", footer=True), encoding="utf-8")
            native = {"native_decode": {"runparts_totals": {"NpOut": 1234, "NpOutPos": 1234, "NpOutRho": 0, "NpOutMov": 0}}}
            result = subject._read_runparts(path, stat_ref(path, 2), {"timeline": {"time_s": [0.0, 0.1]}}, native)
            self.assertEqual(result["totals"]["NpOut"], 1234)
            self.assertEqual(result["footer_comment_count"], 2)

    def test_runparts_rejects_duplicate_or_missing_header_columns(self) -> None:
        for kwargs in ({"duplicate": True}, {"missing": True}):
            with self.subTest(**kwargs), tempfile.TemporaryDirectory() as directory:
                path = Path(directory) / "RunPARTs.csv"
                path.write_text(runparts_text(**kwargs), encoding="utf-8")
                with self.assertRaises(subject.CrosscheckError):
                    subject._read_runparts(path, stat_ref(path, 2), {"timeline": {"time_s": [0.0, 0.1]}}, {"native_decode": {}})

    def test_runparts_rejects_malformed_count(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "RunPARTs.csv"
            path.write_text(runparts_text(malformed_count=True), encoding="utf-8")
            with self.assertRaises(subject.CrosscheckError):
                subject._read_runparts(path, stat_ref(path, 2), {"timeline": {"time_s": [0.0, 0.1]}}, {"native_decode": {}})

    def test_runparts_wrong_timeline_or_total_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "RunPARTs.csv"
            path.write_text(runparts_text(second_time="0.2"), encoding="utf-8")
            native = {"native_decode": {"runparts_totals": {"NpOut": 3, "NpOutPos": 3, "NpOutRho": 0, "NpOutMov": 0}}}
            with self.assertRaises(subject.CrosscheckError):
                subject._read_runparts(path, stat_ref(path, 2), {"timeline": {"time_s": [0.0, 0.1]}}, native)

    def test_same_bytes_replacement_requires_inode_and_times(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            first = root / "first.jsonl"
            second = root / "second.jsonl"
            first.write_bytes(b"same")
            declared = subject._stat(first, "first", allow_deferred=True)
            second.write_bytes(b"same")
            actual = subject._stat(second, "second", allow_deferred=True)
            with self.assertRaises(subject.CrosscheckError):
                subject._require_same_stat(actual, declared, "replacement")

    def test_record_parser_rejects_non_object_and_accepts_non_target_identity(self) -> None:
        self.assertEqual(subject._record_from_line(b'{"zone":0,"idp":999}', 1)["idp"], 999)
        with self.assertRaises(subject.CrosscheckError):
            subject._record_from_line(b"[]", 2)

    def test_claim_boundary_and_contract_compatibility(self) -> None:
        self.assertEqual(subject.SCHEMA, "ds02.stage2.f6-dxyz-typed-native-crosscheck.v2")
        self.assertEqual(subject.CONTRACT_SCHEMA, "ds02.stage2.f6-dxyz-typed-native-crosscheck-contract.v1")
        self.assertEqual(subject.FAMILY_ID, "F6")
        self.assertEqual(subject.CASE_ID, "F6_STAGE1_ANGULAR_RELEASE_DXYZ_S0375_YAWM12_DP025")

    def test_audit_cli_accepts_production_contract_arguments(self) -> None:
        result = subprocess.run([str(subject.VENV), str(subject.SCRIPT), "audit", "--help"], check=True, capture_output=True, text=True)
        self.assertIn("--contract", result.stdout)
        self.assertIn("--output", result.stdout)

    def test_request_uses_existing_contract_path_and_v2_output(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            contract_path = root / "root209-primary-contract.json"
            deferred = {
                role: {"path": str(root / f"{role}.jsonl"), "sha256": "0" * 64}
                for role in ("typed_records", "partout_csv", "runparts_csv")
            }
            contract_path.write_text(json.dumps({"deferred_inputs": deferred, "resource_policy": {}, "claim_boundary": {}}), encoding="utf-8")
            request_path = root / "request.json"
            result = subject._request_from_contract(contract_path, request_path, subject.SCRIPT, subject.VENV)
            self.assertEqual(result["worker_version"], "f6-dxyz-typed-native-crosscheck.v2")
            self.assertEqual(result["command"][result["command"].index("--contract") + 1], str(contract_path.absolute()))
            self.assertEqual(result["command"][-1], "{attempt_root}/f6-dxyz-crosscheck-v2.json")
            self.assertFalse(result["launch_allowed"])


if __name__ == "__main__":
    unittest.main()
