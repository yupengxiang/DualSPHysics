"""CPU-only contract tests for the native F4 material preflight."""

from __future__ import annotations

import json
from pathlib import Path

import h5py
import numpy as np
import pytest

from scripts import f4_tallwall120_material_preflight_v1 as preflight


def _result(*, unknown_fraction: float = 1.0, complete: bool = False) -> dict:
    return {
        "committed_frame": 7,
        "committed_time_s": 0.028,
        "event_window_status": "complete" if complete else "right_censored_or_unresolved",
        "by_source": [{
            "source": 1,
            "unknown_fraction": unknown_fraction,
            "unknown_fraction_max": unknown_fraction,
            "mass_closure_error": 0.0,
            "reliable_path_coverage": 1.0 - unknown_fraction,
        }],
    }


def test_result_summary_keeps_full_seed_denominator_and_right_censor() -> None:
    summary = preflight.result_summary(_result(unknown_fraction=1.0))

    assert summary["seed_denominator"] == 512
    assert summary["unknown_count"] == 512
    assert summary["unknown_gate_limit"] == 0.01
    assert summary["unknown_gate_pass"] is False
    assert summary["right_censored"] is True
    assert summary["event_window_complete"] is False
    assert summary["mass_closed"] is True


def test_result_summary_does_not_turn_small_unknown_count_into_t2() -> None:
    summary = preflight.result_summary(_result(unknown_fraction=1 / 512, complete=True))

    assert summary["unknown_gate_pass"] is True
    assert summary["unknown_count"] == 1
    assert summary["event_window_complete"] is True
    # The helper reports a gate observation only; no qualification field is
    # produced from a single result.
    assert "T2_macro" not in summary


def test_inspect_source_rejects_nonmonotone_time_axis(tmp_path: Path) -> None:
    source = tmp_path / "source.h5"
    with h5py.File(source, "w") as handle:
        handle.create_dataset("time", data=np.asarray([0.0, 0.0]))
        handle.create_dataset("position", shape=(2, 1, 3), dtype="f8")
        handle.create_dataset("velocity", shape=(2, 1, 3), dtype="f4")
        handle.create_dataset("valid", data=np.ones((2, 1), dtype=bool))
        handle.create_dataset("mass", data=np.ones((2, 1), dtype="f4"))
        handle.create_dataset("source_label_initial_mk", data=np.ones(1, dtype="i2"))
    with pytest.raises(ValueError, match="source H5 hash"):
        preflight.inspect_source(
            source,
            archive_path=tmp_path / "archive.json",
            audit_path=tmp_path / "audit.json",
            result_path=tmp_path / "result.json",
            prepared_path=tmp_path / "prepared.json",
            range_root_path=tmp_path / "range.json",
            completion_path=tmp_path / "completion.json",
        )


def test_versioned_receipt_is_explicitly_nonqualifying() -> None:
    root = Path(__file__).resolve().parents[1]
    receipt = root / (
        "campaigns/core-v1/material/evidence/"
        "f4-tallwall120-native-cell14-material-preflight-20260921.json"
    )
    if not receipt.is_file():
        pytest.skip("bounded native preflight receipt is generated by the CPU canary command")
    value = json.loads(receipt.read_text(encoding="utf-8"))
    assert value["schema"] == preflight.SCHEMA
    assert value["source_t1_binding"]["scope"]["T1_numerical"] is True
    assert value["source_t1_binding"]["scope"]["status"] == "qualified"
    assert value["cadence_contract"]["cadence_substitution"] is False
    assert value["cadence_contract"]["no_stride_or_synthetic_cadence"] is True
    assert value["execution_constraints"]["gpu_started"] is False
    assert value["execution_constraints"]["solver_started"] is False
    assert value["execution_constraints"]["queue_mutation"] == 0
    assert value["execution_constraints"]["registry_mutation"] == 0
    assert value["execution_constraints"]["central_ledger_mutation"] == 0
    assert value["qualification"]["T2_macro"] is False
    assert value["qualification"]["T2_path"] is False
    assert value["qualification"]["qualification_credit"] == "none"
    gate = value["gate_evaluation"]
    assert gate["seed_denominator"] == 512
    assert gate["right_censored"] is True
    assert gate["unknown_gate_pass"] is False
