"""Contract tests for the read-only F4 first-failure root-cause audit."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from scripts import f4_tallwall120_root_cause_audit_v1 as audit


def test_candidate_contracts_keep_all_scientific_gates_fixed() -> None:
    contracts = audit._variant_contracts()
    audit.validate_candidate_contracts(contracts)

    baseline = contracts["baseline24"]
    assert baseline["unknown_fraction_limit"] == 0.01
    for name, contract in contracts.items():
        assert contract["fixed_gate"] == baseline["fixed_gate"]
        assert contract["unknown_fraction_limit"] == 0.01
        assert contract["event_gate_changed"] is False
        assert contract["unknown_gate_changed"] is False
        assert contract["cdf_changed"] is False
        assert contract["qualification_credit"] == "none"


def test_candidate_contract_rejects_unknown_limit_change() -> None:
    contracts = audit._variant_contracts()
    contracts["f4_ess32_v2"]["unknown_fraction_limit"] = 0.02
    with pytest.raises(ValueError, match="unknown fraction limit"):
        audit.validate_candidate_contracts(contracts)


def test_generated_audit_attributes_first_failure_to_reconstruction_only() -> None:
    root = Path(__file__).resolve().parents[1]
    path = root / (
        "campaigns/core-v1/material/evidence/"
        "f4-tallwall120-native-cell14-root-cause-audit-20260921.json"
    )
    if not path.is_file():
        pytest.skip("root-cause audit is generated by the CPU-only audit command")
    value = json.loads(path.read_text(encoding="utf-8"))
    assert value["transition"]["first_failure_cohort_count"] == 128
    assert value["baseline_evaluation"]["baseline_exact_trace_match"] is True
    assert value["root_cause"]["primary"] == "field1 reconstruction_error_gate"
    assert value["baseline_evaluation"]["stage0"]["cohort_union_component_fail_counts"] == {
        "anisotropy": 0,
        "ess": 0,
        "rank": 0,
        "reconstruction": 125,
        "support_distance": 0,
    }
    assert value["baseline_evaluation"]["stage1"]["cohort_union_component_fail_counts"] == {
        "anisotropy": 0,
        "ess": 0,
        "rank": 0,
        "reconstruction": 3,
        "support_distance": 0,
    }
    assert value["qualification"]["T2_macro"] is False
    assert value["qualification"]["T2_path"] is False
    assert value["qualification"]["qualification_credit"] == "none"
    assert value["execution_constraints"]["existing_trace_modified"] is False
