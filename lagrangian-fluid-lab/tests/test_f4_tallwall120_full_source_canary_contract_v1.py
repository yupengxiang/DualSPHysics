"""Tests for the proposal-only full-source F4 canary contract."""

from __future__ import annotations

import copy
import json
from pathlib import Path

import pytest

from scripts import f4_tallwall120_full_source_canary_contract_v1 as contract


def test_generated_contract_binds_full_window_and_new_output_stem() -> None:
    root = Path(__file__).resolve().parents[1]
    path = root / (
        "campaigns/core-v1/material/evidence/"
        "f4-tallwall120-native-cell14-f4-ess32-full-source-canary-contract-20260921.json"
    )
    if not path.is_file():
        pytest.skip("proposal contract is generated by the contract builder")
    value = json.loads(path.read_text(encoding="utf-8"))
    assert value["status"] == "proposal_only_deferred_after_one_transition_failure"
    assert value["source_window"]["frame_start"] == 0
    assert value["source_window"]["frame_end"] == 1085
    assert value["source_window"]["frame_count"] == 1086
    assert value["source_window"]["time_end_s"] == pytest.approx(4.340002980805959)
    assert value["execution"]["phase_0"]["stop_after_frame"] == 40
    assert value["execution"]["phase_1"]["resume_from_frame"] == 40
    assert value["execution"]["phase_1"]["stop_after_frame"] == 1085
    assert value["execution"]["output_stem_is_new"] is True
    assert value["execution"]["existing_trace_reuse"]["binding_only"] is True
    assert value["execution"]["existing_trace_reuse"]["candidate_output_reuse"] is False


def test_generated_contract_is_cpu_only_and_zero_credit() -> None:
    root = Path(__file__).resolve().parents[1]
    path = root / (
        "campaigns/core-v1/material/evidence/"
        "f4-tallwall120-native-cell14-f4-ess32-full-source-canary-contract-20260921.json"
    )
    if not path.is_file():
        pytest.skip("proposal contract is generated by the contract builder")
    value = json.loads(path.read_text(encoding="utf-8"))
    assert value["candidate"]["unknown_fraction_limit"] == 0.01
    assert value["candidate"]["qualification_credit"] == "none"
    assert value["candidate"]["event_gate_changed"] is False
    assert value["candidate"]["cdf_changed"] is False
    assert value["resource_profile"]["execution_mode"].startswith("CPU-only")
    assert value["resource_profile"]["cKDTree_workers"] == 1
    assert value["resource_profile"]["budgets"]["max_rss_kib"] == 1048576
    assert value["execution_constraints"]["proposal_only"] is True
    assert value["execution_constraints"]["solver_started"] is False
    assert value["execution_constraints"]["gpu_started"] is False
    assert value["execution_constraints"]["scientific_denominator_changed"] is False
    assert value["candidate"]["one_transition_counterfactual"]["counterfactual_cohort_survivors"] == 0


def test_contract_rejects_candidate_trace_reuse() -> None:
    root = Path(__file__).resolve().parents[1]
    path = root / (
        "campaigns/core-v1/material/evidence/"
        "f4-tallwall120-native-cell14-f4-ess32-full-source-canary-contract-20260921.json"
    )
    if not path.is_file():
        pytest.skip("proposal contract is generated by the contract builder")
    value = json.loads(path.read_text(encoding="utf-8"))
    broken = copy.deepcopy(value)
    broken["execution"]["existing_trace_reuse"]["candidate_output_reuse"] = True
    with pytest.raises(ValueError, match="old trace"):
        contract.validate_contract(broken)

